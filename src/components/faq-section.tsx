/** Collapsible region that animates to its content height. */
function Collapse({
  open,
  id,
  children,
}: {
  open: boolean;
  id: string;
  children: React.ReactNode;
}) {
  return (
    <div
      id={id}
      className={`grid transition-[grid-template-rows,opacity] duration-300 ease-out motion-reduce:transition-none ${
        open ? "grid-rows-[1fr] opacity-100" : "grid-rows-[0fr] opacity-0"
      }`}
    >
      <div className="min-h-0 overflow-hidden">{children}</div>
    </div>
  );
}

function QuestionCard({
  question,
  open,
  onToggle,
}: {
  question: Question;
  open: boolean;
  onToggle: () => void;
}) {
  const id = useId();
  const expandable = Boolean(question.a);
  const label = (
    <>
      <span className="min-w-px flex-1 text-left font-sans text-[16px] font-medium leading-[1.2] text-black [text-box-edge:cap_alphabetic] [text-box-trim:trim-both]">
        {question.q}
      </span>
      <img
        src={open ? "/figma/faq-minus.svg" : "/figma/faq-plus.svg"}
        alt=""
        className="block size-[24px] shrink-0"
      />
    </>
  );

  return (
    <div className="w-full rounded-[18px] bg-white py-[7px] ring-1 ring-inset ring-[#efefef] drop-shadow-[0px_4px_7.65px_rgba(0,0,0,0.06)]">
      {expandable ? (
        <button
          type="button"
          aria-expanded={open}
          aria-controls={id}
          onClick={onToggle}
          className={`flex w-full items-center justify-between pl-[12px] pr-[8px] ${open ? "pb-[8px] pt-[12px]" : "py-[12px]"}`}
        >
          {label}
        </button>
      ) : (
        <div className="flex w-full items-center justify-between py-[12px] pl-[12px] pr-[8px]">
          {label}
        </div>
      )}
      {question.a && (
        <Collapse open={open} id={id}>
          <p className="px-[12px] pb-[16px] pt-[8px] font-sans text-[16px] font-medium leading-[1.2] text-[#9d9fa0] [text-box-edge:cap_alphabetic] [text-box-trim:trim-both]">
            {question.a}
          </p>
        </Collapse>
      )}
    </div>
  );
}

function CategoryGroup({
  category,
  defaultOpen,
}: {
  category: Category;
  defaultOpen: boolean;
}) {
  const id = useId();
  const [open, setOpen] = useState(defaultOpen);
  const [openQuestion, setOpenQuestion] = useState<number | null>(
    defaultOpen ? 0 : null,
  );
  const hasQuestions = category.questions.length > 0;

  const header = (
    <>
      <span className="whitespace-nowrap font-sans text-[16px] font-medium leading-[1.2] text-black [text-box-edge:cap_alphabetic] [text-box-trim:trim-both]">
        {category.title}
      </span>
      <span className="flex h-[12px] w-[24px] shrink-0 items-center justify-center">
        <img
          src="/figma/faq-chevron.svg"
          alt=""
          className="block h-[24px] w-[12px] max-w-none rotate-90"
        />
      </span>
    </>
  );

  return (
    <div className="flex w-full flex-col items-center">
      {hasQuestions ? (
        <button
          type="button"
          aria-expanded={open}
          aria-controls={id}
          onClick={() => setOpen((o) => !o)}
          className="flex w-full items-center justify-between py-[4px] pl-[11px]"
        >
          {header}
        </button>
      ) : (
        <div className="flex w-full items-center justify-between py-[4px] pl-[11px]">
          {header}
        </div>
      )}
      {hasQuestions && (
        <Collapse open={open} id={id}>
          <div className="flex flex-col gap-[12px] pt-[16px]">
            {category.questions.map((question, i) => (
              <QuestionCard
                key={i}
                question={question}
                open={openQuestion === i}
                onToggle={() =>
                  setOpenQuestion((cur) => (cur === i ? null : i))
                }
              />
            ))}
          </div>
        </Collapse>
      )}
    </div>
  );
}

